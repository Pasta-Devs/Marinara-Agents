/* global normalizeForgeAudio */
export function forgeAudioFields() {
  const volume = (channel, fallback) => ({
    id: `audio.${channel}Volume`,
    step: "look",
    settings: "visual",
    group: "audioMix",
    type: "range",
    label: forgeAudioEnglish[`audio.settings.${channel}`],
    min: 0,
    max: 1,
    stepBy: 0.01,
    default: fallback,
    rangeLabel: (value) => `${Math.round(Number(value) * 100)}%`,
  });
  const defaults = normalizeForgeAudio();
  return [
    {
      id: "audio.tts",
      step: "sources",
      settings: "sources",
      group: "audio",
      type: "toggle",
      label: forgeAudioEnglish["audio.settings.tts"],
      hint: forgeAudioEnglish["audio.settings.ttsHint"],
      default: false,
    },
    {
      id: "audio.combatVoices",
      step: "sources",
      settings: "sources",
      group: "audio",
      type: "toggle",
      label: forgeAudioEnglish["audio.settings.combatVoices"],
      hint: forgeAudioEnglish["audio.settings.combatVoicesHint"],
      default: false,
    },
    {
      id: "audio.generate",
      step: "sources",
      settings: "sources",
      group: "audio",
      type: "toggle",
      label: forgeAudioEnglish["audio.settings.generate"],
      hint: forgeAudioEnglish["audio.settings.generateHint"],
      default: false,
    },
    {
      id: "audio.audioConnectionId",
      step: "sources",
      settings: "sources",
      group: "audio",
      type: "select",
      optionsFrom: "forgeAudioConnections",
      label: forgeAudioEnglish["audio.settings.connection"],
      emptyOption: forgeAudioEnglish["audio.settings.connectionEmpty"],
      hint: forgeAudioEnglish["audio.settings.connectionHint"],
      showIf: (values) => values["audio.generate"] === true,
    },
    {
      id: "audio.homeMusic",
      step: "look",
      settings: "visual",
      group: "audioMix",
      type: "select",
      optionsFrom: "forgeSoundtracks",
      label: forgeAudioEnglish["audio.settings.homeMusic"],
      emptyOption: forgeAudioEnglish["audio.settings.homeMusicDefault"],
      hint: forgeAudioEnglish["audio.settings.homeMusicHint"],
      default: "",
    },
    volume("music", defaults.musicVolume),
    volume("dialogue", defaults.dialogueVolume),
    volume("sfx", defaults.sfxVolume),
    {
      id: "audio.autoplayPauseSeconds",
      step: "look",
      settings: "visual",
      group: "playback",
      type: "range",
      label: forgeAudioEnglish["audio.settings.pause"],
      hint: forgeAudioEnglish["audio.settings.pauseHint"],
      min: 0,
      max: 30,
      stepBy: 0.5,
      default: defaults.autoplayPauseSeconds,
      rangeLabel: (value) => forgeAudioEnglish["audio.seconds"].replace("{seconds}", String(Number(value))),
    },
  ];
}
