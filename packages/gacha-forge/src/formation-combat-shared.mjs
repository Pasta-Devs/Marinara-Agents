/**
 * The most power an ability may carry. Power means, per effect: damage/aoe_damage/drain/execute % of ATK per hit;
 * dot % of ATK each of the target's turns; heal/restore % of each target's max HP; revive % of max HP regained;
 * shield % of the target's max HP absorbed; regen % of max HP each of the target's turns; buff/debuff % ATK or DEF
 * (crit: chance points); stun/silence the chance to land; energy points of the user's element; summon the Echo's
 * share of the user's stats. Taunt, immune, cleanse, swap and shuffle ignore power.
 */
// Power per budget point, the most an effect may carry, and the share kept when it reaches a whole row or team.
export const forgeFormationShares = {
  damage: 1,
  aoe_damage: 1,
  drain: 0.85,
  execute: 0.85,
  dot: 0.35,
  heal: 0.08,
  shield: 0.1,
  regen: 0.025,
  buff: 0.2,
  debuff: 0.2,
  restore: 0.3,
  revive: 0.3,
};
export const forgeFormationCeilings = { shield: 50, buff: 60, debuff: 60, restore: 100, revive: 100 };
export const forgeFormationSpread = 0.7;

/** The budget an ability's power is measured against. */
export function forgeFormationBudget(slot, cost = 0, row = "front") {
  if (slot === "standard") return 100 + 30 * cost;
  if (slot === "ultimate") return Math.min(320, 160 + 20 * cost);
  return row === "back" ? 160 : 110;
}

export function forgeFormationPowerCap(ability, slot, row = "front") {
  const cost = slot === "passive" ? 0 : Number(ability?.cost) || 0,
    budget = forgeFormationBudget(slot, cost, row),
    effect = ability?.effect,
    share = forgeFormationShares[effect];
  if (share) {
    const spread =
      !["restore", "revive"].includes(effect) && (forgeFormationMulti.has(ability?.target) || effect === "aoe_damage");
    return Math.min(
      forgeFormationCeilings[effect] || forgeFormationMaxPower,
      Math.round(budget * share * (spread ? forgeFormationSpread : 1)),
    );
  }
  if (effect === "stun" || effect === "silence")
    return slot === "ultimate" ? 100 : slot === "passive" ? 35 : Math.min(100, 25 + 25 * cost);
  if (effect === "energy") return Math.min(3, 1 + Math.floor(budget / 150));
  if (effect === "summon") return 60;
  return 0;
}

function forgeFormationFitTarget(effect, target) {
  if (["aoe_damage", "shuffle"].includes(effect)) return "all_enemies";
  if (["taunt", "energy", "summon"].includes(effect)) return "self";
  if (effect === "swap") return "enemy";
  if (effect === "revive") return target === "allies" ? "allies" : "ally";
  if (forgeFormationOffense.has(effect)) {
    if (["all_enemies", "allies", "front_row", "back_row"].includes(target))
      return target === "all_enemies" ? "all_enemies" : "front_row";
    return "enemy";
  }
  if (target === "enemy") return "ally";
  if (target === "all_enemies") return "allies";
  return target || (effect === "restore" ? "allies" : "ally");
}

const forgeFormationSlotDefaults = {
  standard: { name: "Strike", effect: "damage" },
  ultimate: { name: "Finisher", effect: "damage" },
  passive: { name: "Instinct", effect: "shield" },
};

function forgeFormationAbility(raw, slot, preferredRow) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  // An unknown effect or a missing name takes its slot's plain default instead of failing a paid kit.
  const statEffect = forgeFormationStatEffects[forgeFormationKey(raw.effect)];
  const picked = statEffect?.[0] || forgeFormationPick(forgeFormationEffects, forgeFormationAliases.effect, raw.effect);
  const effect = picked || forgeFormationSlotDefaults[slot].effect,
    name = forgeFormationText(raw.name, 80) || forgeFormationSlotDefaults[slot].name;
  const crowd = ["heal_all", "mass_heal", "group_heal"].includes(forgeFormationKey(raw.effect));
  const ability = {
    name,
    description: forgeFormationText(raw.description, 500),
    effect,
    target: forgeFormationFitTarget(
      effect,
      crowd
        ? "allies"
        : picked
          ? forgeFormationPick(forgeFormationTargets, forgeFormationAliases.target, raw.target)
          : slot === "passive"
            ? "self"
            : "enemy",
    ),
    power: 0,
    duration: forgeFormationClamp(forgeFormationNumber(raw.duration) ?? 2, 1, 3),
  };
  if (effect === "buff" || effect === "debuff")
    ability.stat =
      forgeFormationPick(["atk", "def", "crit"], forgeFormationAliases.stat, raw.stat) || statEffect?.[1] || "atk";
  if (slot === "passive") {
    let trigger =
      forgeFormationPick(forgeFormationTriggers, forgeFormationAliases.trigger, raw.trigger) || "turn_start";
    const row =
      forgeFormationPick(["front", "back", "both"], forgeFormationAliases.row, raw.row) ||
      (preferredRow === "back" ? "back" : preferredRow === "hybrid" ? "both" : "front");
    // A passive must sit where its trigger can fire: the Back Row is never hit, never attacks and never casts.
    if (row === "back")
      trigger =
        { on_hit: "ally_hit", on_attack: "ally_attack", on_ult: "ally_ult" }[trigger] ||
        (["on_kill", "on_death", "enter_front"].includes(trigger) ? "turn_start" : trigger);
    if (row === "front" && trigger === "enter_back") trigger = "turn_start";
    ability.trigger = trigger;
    ability.row = row;
    // Immunity every turn would make a unit unkillable, so a passive grants a shield instead.
    if (effect === "immune") Object.assign(ability, { effect: "shield", target: "self" });
    // A full restore is an Ultimate's job; repeated every turn it would stall a fight.
    if (effect === "restore") ability.effect = "heal";
  } else {
    const ultimate = slot === "ultimate";
    if (!ultimate && effect === "restore") ability.effect = "heal";
    // Immunity is a saved-up Ultimate; a Normal skill grants a shield instead.
    if (!ultimate && effect === "immune")
      Object.assign(ability, { effect: "shield", target: ability.target === "allies" ? "allies" : "self" });
    let cost = forgeFormationClamp(
      forgeFormationNumber(raw.cost) ?? (ultimate ? 4 : 0),
      ultimate ? 2 : 0,
      ultimate ? 8 : 4,
    );
    // Board-changing and protective Normal skills must be paid for, or they would repeat every turn.
    if (!ultimate && ["swap", "shuffle", "revive"].includes(effect)) cost = Math.max(2, cost);
    ability.cost = cost;
    if (ultimate) ability.elementCost = forgeFormationClamp(forgeFormationNumber(raw.elementCost) ?? 1, 1, cost);
  }
  // A support's own action is deliberately weak: its Normal skill keeps 60% of the limit.
  const cap = Math.round(
    forgeFormationPowerCap(ability, slot, ability.row) *
      (slot === "standard" && preferredRow === "back" && !["stun", "silence", "energy"].includes(effect) ? 0.6 : 1),
  );
  const floor = effect === "revive" ? 10 : 0;
  ability.power = cap ? forgeFormationClamp(forgeFormationNumber(raw.power) ?? cap, floor, cap) : 0;
  if (effect === "energy") ability.power = Math.max(1, ability.power);
  if (effect === "summon") ability.power = Math.max(20, ability.power);
  return ability;
}

/**
 * Reads a model-written or stored kit leniently: synonyms are remapped, numbers clamped to the budgets and
 * impossible passive rows moved to triggers that can fire, so a fixable kit never costs a paid retry. Only a
 * structurally broken kit (a missing ability, name or unknown effect) is refused. `rarity` (generation only)
 * drops signature traits below five stars; the stored version is preserved.
 */
export function normalizeForgeFormationKit(raw, { rarity, fallback } = {}) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  const preferredRow =
    forgeFormationPick(["front", "back", "hybrid"], forgeFormationAliases.preferredRow, raw.preferredRow) ||
    fallback?.preferredRow ||
    "front";
  // `fallback` (an enemy's classic kit) fills a slot the model left out, so a boss guide is never paid for twice.
  const slot = (key, ...names) =>
    forgeFormationAbility(
      names.map((name) => raw[name]).find((value) => value && typeof value === "object"),
      key,
      preferredRow,
    ) || (fallback ? forgeFormationAbility(fallback[key], key, preferredRow) : null);
  const standard = slot("standard", "standard", "normal"),
    ultimate = slot("ultimate", "ultimate", "ult"),
    passive = slot("passive", "passive");
  if (!standard || !ultimate || !passive) return null;
  // The Front Row is there to fight: a fighter with nothing that reaches the enemy strikes with its Normal skill.
  // A passive counts only when it deals damage in front without the unit attacking first: it has power, and
  // it does not wait for an attack (on_attack) or a kill (on_kill), or fire only from the Back Row.
  const strikingPassive =
    forgeFormationStrikes.has(passive.effect) &&
    passive.power > 0 &&
    passive.row !== "back" &&
    !["on_attack", "on_kill"].includes(passive.trigger);
  if (
    preferredRow !== "back" &&
    !forgeFormationOffense.has(standard.effect) &&
    !forgeFormationOffense.has(ultimate.effect) &&
    !strikingPassive
  ) {
    Object.assign(standard, { effect: "damage", target: "enemy", description: "" });
    delete standard.stat;
    standard.power = forgeFormationPowerCap(standard, "standard");
  }
  const traits = [];
  for (const trait of Array.isArray(raw.traits) ? raw.traits : []) {
    const kind = forgeFormationKey(typeof trait === "string" ? trait : trait?.kind);
    if (!forgeFormationTraitKinds.includes(kind) || traits.some((entry) => entry.kind === kind)) continue;
    const perk = forgeFormationHybridPerks.includes(kind);
    // At most one hybrid perk (hybrids only) and one five-star signature.
    if (perk ? preferredRow !== "hybrid" : rarity != null && Number(rarity) < 5) continue;
    if (traits.some((entry) => forgeFormationHybridPerks.includes(entry.kind) === perk)) continue;
    const [min, max, fallback] = forgeFormationTraitPower[kind];
    traits.push({ kind, power: forgeFormationClamp(forgeFormationNumber(trait?.power) ?? fallback, min, max) });
  }
  return {
    version: Number.isSafeInteger(raw.version) ? raw.version : 1,
    preferredRow,
    standard,
    ultimate,
    passive,
    traits,
  };
}

export function forgeFormationReady(unit) {
  return !!normalizeForgeFormationKit(unit?.formationKit);
}

/** Encounter rules are kept when they can be played and dropped when they cannot, never failing a guide. */
export function normalizeForgeFormationRules(raw, enemies = []) {
  const rules = [];
  for (const rule of Array.isArray(raw) ? raw.slice(0, 4) : []) {
    const kind = forgeFormationKey(rule?.kind);
    const description = forgeFormationText(rule?.description, 400);
    if (!description || rules.length === 2 || rules.some((entry) => entry.kind === kind)) continue;
    if (kind === "element_barrier" && Array.isArray(rule.elements)) {
      const elements = [...new Set(rule.elements.map((element) => String(element).toLowerCase()))].filter((element) =>
        forgeFormationElements.includes(element),
      );
      if (elements.length) rules.push({ kind, description, elements });
    } else if (kind === "defeat_order" && Array.isArray(rule.order)) {
      const order = [...new Set(rule.order)].filter(
        (index) => Number.isInteger(index) && index >= 0 && index < enemies.length,
      );
      if (order.length >= 2) rules.push({ kind, description, order: order.slice(0, 3) });
    }
  }
  return rules;
}

/**
 * The payment for an ability from a bank, or null. Light and Dark stand in 1:1 for the element an Ultimate needs.
 * Native energy pays the element part first; the rest uses other elements before native, and Light/Dark last.
 */
export function forgeFormationPayment(bank, ability, affinity) {
  const element = String(affinity || "").toLowerCase(),
    cost = Math.max(0, Number(ability?.cost) || 0),
    required = Math.min(cost, Math.max(0, Number(ability?.elementCost) || 0));
  const left = Object.fromEntries(forgeFormationElements.map((key) => [key, Math.max(0, Number(bank?.[key]) || 0)]));
  const payment = forgeFormationZero();
  const take = (key, amount) => {
    const used = Math.min(left[key], amount);
    left[key] -= used;
    payment[key] += used;
    return used;
  };
  const wild = ["light", "dark"].filter((key) => key !== element);
  let need = required - take(element, required);
  for (const key of wild.slice().sort((a, b) => left[b] - left[a])) need -= take(key, need);
  if (need > 0) return null;
  let rest = cost - required;
  const order = forgeFormationElements
    .filter((key) => key !== element && !wild.includes(key))
    .sort((a, b) => left[b] - left[a] || forgeFormationElements.indexOf(a) - forgeFormationElements.indexOf(b));
  for (const key of [...order, element, ...wild]) rest -= take(key, rest);
  return rest > 0 ? null : payment;
}

/** Spending each queued action in order: what it pays, whether it can, and the bank left afterwards. */
export function forgeFormationProjection(formation, entries = []) {
  const bank = { ...forgeFormationZero(), ...formation?.bank };
  const results = entries.map((entry) => {
    const fighter = formation?.fighters?.find((unit) => unit.id === entry.actorId);
    const skill = entry.action === "ultimate" ? fighter?.ultimate : entry.action === "normal" ? fighter?.normal : null;
    if (!skill) return { entry, payment: null, ok: true };
    const payment = forgeFormationPayment(bank, skill, fighter.aff);
    if (payment) for (const key of forgeFormationElements) bank[key] -= payment[key];
    // A planned energy cast adds its energy before the next step pays, as the engine resolves it.
    if (payment && skill.effect === "energy") bank[fighter.aff] += Math.max(1, Math.round(Number(skill.power) || 0));
    return { entry, payment, ok: !!payment };
  });
  return { bank, results };
}

export function forgeFormationTeamError(actors) {
  if (!Array.isArray(actors) || !actors.length || actors.length > 6) return "formation-team-size";
  if (new Set(actors.map((actor) => actor.id)).size !== actors.length) return "formation-team-duplicate";
  const front = actors.filter((actor) => actor.position !== "back").length;
  return front < 1 || front > 3 || actors.length - front > 3 ? "formation-rows" : null;
}

// Compatibility for enemies without a generated kit; heroes must have an authored generated kit.
export function forgeFormationEnemyKit(enemy) {
  const skill = enemy?.skill && typeof enemy.skill === "object" ? enemy.skill : {};
  const legacyPower = (value) => {
    const number = forgeFormationNumber(value);
    return number == null ? 100 : number;
  };
  const ability = (source, cost, scale = 1) => ({
    name: forgeFormationText(source?.name, 80) || "Strike",
    description: forgeFormationText(source?.description, 500),
    effect: forgeFormationPick(forgeFormationEffects, forgeFormationAliases.effect, source?.effect) || "damage",
    target: source?.target,
    power: Math.max(0, Math.round(legacyPower(source?.power) * scale)),
    stat: source?.stat,
    duration: 2,
    cost,
  });
  const passiveSource = enemy?.passive && typeof enemy.passive === "object" ? enemy.passive : null;
  return normalizeForgeFormationKit({
    preferredRow: enemy?.position === "back" ? "back" : "front",
    standard: ability(skill, 0, 0.6),
    ultimate: { ...ability(skill, 3), elementCost: 1 },
    passive: passiveSource
      ? { ...ability(passiveSource, 0), trigger: passiveSource.trigger, row: "both" }
      : { name: "Reserve", effect: "shield", target: "self", power: 0, trigger: "turn_start", row: "both" },
    traits: [],
  });
}

export function* forgeFormationBattle({
  allies = [],
  enemies = [],
  seed = 1,
  rules = [],
  formationRevision = FORGE_FORMATION_RULES,
} = {}) {
  let randomSeed = seed >>> 0 || 1;
  const random = () => {
    randomSeed = (Math.imul(randomSeed, 1664525) + 1013904223) >>> 0;
    return randomSeed / 4294967296;
  };
  const steps = [],
    log = [],
    banks = { ally: forgeFormationZero(), enemy: forgeFormationZero() },
    floors = { ally: 0, enemy: 0 };
  const actors = [
    ...allies.map((unit) => ({ unit, side: "ally" })),
    ...enemies.map((unit) => ({ unit, side: "enemy" })),
  ].map(({ unit, side }, index) => {
    const stats = unit.stats || {},
      power = Number(unit.power) > 0 ? Number(unit.power) : 1,
      hpMax = Math.round(20 + (Number(stats.hp) || 50) * power * 6);
    const kit =
      normalizeForgeFormationKit(unit.formationKit) || (side === "enemy" ? forgeFormationEnemyKit(unit) : null);
    return {
      ...forgeFormationCopy(unit),
      id: String(unit.id || `${side}-${index}`),
      side,
      aff: String(unit.affinity || "fire").toLowerCase(),
      position: unit.position === "back" ? "back" : "front",
      kit,
      hp: hpMax,
      hpMax,
      atk: (Number(stats.atk) || 50) * power,
      def: (Number(stats.def) || 50) * power,
      spd: Number(stats.spd) || 50,
      crit: forgeFormationClamp(Number.isFinite(Number(stats.crit)) ? Number(stats.crit) : 15, 0, 100),
      critDmg: Math.max(100, Number(stats.critDmg) || 150),
      mech: Array.isArray(unit.mech) ? unit.mech.slice() : [],
      shield: 0,
      statuses: [],
      alive: true,
      acted: false,
      entered: 0,
      advanced: -9,
      revived: false,
      triggers: new Set(),
      lastCast: null,
      token: false,
      ownerId: "",
      guard: Array.isArray(unit.mech) && unit.mech.includes("guard") ? 100 : 0,
      broken: 0,
      enraged: false,
      activations: 0,
      charging: "",
      controlled: -9,
      warded: -9,
      saving: false,
      damageBonus: 1,
      critBonus: 0,
    };
  });
  rules = normalizeForgeFormationRules(rules, enemies);
  const team = (side) => actors.filter((actor) => actor.side === side),
    live = (side) => team(side).filter((actor) => actor.alive),
    fronts = (side) => live(side).filter((actor) => actor.position === "front"),
    fighters = (side) => fronts(side).filter((actor) => !actor.token),
    supports = (side) => live(side).filter((actor) => actor.position === "back" && !actor.token),
    opponent = (side) => (side === "ally" ? "enemy" : "ally"),
    byId = (id) => actors.find((actor) => actor.id === String(id ?? "")),
    hpShare = (actor) => actor.hp / actor.hpMax,
    weakest = (list) =>
      list.slice().sort((a, b) => hpShare(a) - hpShare(b) || actors.indexOf(a) - actors.indexOf(b))[0];
  const ordered = rules.find((rule) => rule.kind === "defeat_order")?.order || [];
  const pinned = new Set(ordered.map((index) => team("enemy")[index]?.id).filter(Boolean));
  for (const id of pinned) {
    const actor = byId(id);
    if (actor.position === "back" && fronts("enemy").length < 3) actor.position = "front";
  }
  const barrier = rules.find((rule) => rule.kind === "element_barrier");
  let turn = 0,
    round = 0,
    tokenSequence = 0,
    result = null,
    depth = 0;
  const emit = (events, ms = 550) => {
    if (!events.length) return;
    const state = events.findLast((event) => event.op === "statuses");
    steps.push({
      d: ms,
      events: events.filter((event) => event.op !== "statuses"),
      ...(state ? { st: state.byId } : {}),
    });
  };
  const hpEvent = (actor, op = "hp", amount) => ({
    op,
    id: actor.id,
    hp: Math.max(0, Math.round(actor.hp)),
    hpMax: actor.hpMax,
    hpPct: Math.max(0, Math.round(hpShare(actor) * 100)),
    pct: Math.max(0, Math.round(hpShare(actor) * 100)),
    ...(amount == null ? {} : { amount }),
  });
  const bankEvent = (side) => ({ op: "formation-bank", side, bank: { ...banks[side] } });
  const status = (actor, kind) => actor.statuses.find((entry) => entry.kind === kind);
  const trait = (actor, kind) => actor.kit?.traits.find((entry) => entry.kind === kind);
  const scalar = (actor, stat) => {
    let value = 1;
    for (const entry of actor.statuses) if (entry.stat === stat) value += entry.value / 100;
    const solo = trait(actor, "solo_front");
    const alone = solo && actor.position === "front" && fighters(actor.side).length === 1;
    if (alone && (stat === "atk" || stat === "def")) value += solo.power / 100;
    return forgeFormationClamp(value, 0.4, alone ? 3 : 2);
  };
  const chips = { dot: "burn", regen: "fregen", immune: "fimmune", marked: "fmarked", charging: "fcharging" };
  const statuses = () => ({
    op: "statuses",
    byId: Object.fromEntries(
      actors
        .filter((actor) => actor.alive || !actor.token)
        .map((actor) => [
          actor.id,
          [
            ...actor.statuses.map((entry) => ({
              k: entry.stat === "crit" ? "fcrit" : entry.stat || chips[entry.kind] || entry.kind,
              v: entry.kind === "stun" ? 1 : entry.value,
              r: entry.turns,
            })),
            ...(actor.alive && actor.shield > 0 ? [{ k: "shield", v: Math.round(actor.shield) }] : []),
          ],
        ]),
    ),
  });
  const addStatus = (target, kind, value, turns, from, stat) => {
    const existing = target.statuses.find((entry) => entry.kind === kind && entry.stat === stat);
    if (existing) {
      if (Math.abs(value) >= Math.abs(existing.value)) existing.value = value;
      existing.turns = Math.max(existing.turns, turns);
      existing.applied = turn;
      existing.from = from;
    } else target.statuses.push({ kind, value, turns, applied: turn, from, ...(stat ? { stat } : {}) });
  };
  const immune = (target, source) => source.side !== target.side && !!status(target, "immune");
  const orderBlocks = (target) => {
    if (!pinned.has(target.id)) return false;
    const next = ordered.map((index) => team("enemy")[index]).find((actor) => actor?.alive);
    return !!next && next !== target;
  };
  const blockedReason = (source, target) => {
    if (target.position !== "front") return "back";
    if (target.side === "enemy" && barrier && !barrier.elements.includes(source.aff)) return "barrier";
    if (target.side === "enemy" && orderBlocks(target)) return "order";
    return null;
  };
  const canTarget = (source, target) => target.alive && target.side !== source.side && !blockedReason(source, target);
  const offensive = (ability) => forgeFormationOffense.has(ability?.effect);
  const fallenOf = (side) => team(side).filter((actor) => !actor.alive && !actor.token && !actor.revived);
  const seatFree = (side, row) =>
    row === "front" ? fronts(side).length < 3 || fronts(side).some((actor) => actor.token) : supports(side).length < 3;
  // Only Swap reaches into the Back Row, and only past a barrier its element can cross.
  const swapPool = (source) =>
    live(opponent(source.side)).filter(
      (actor) =>
        actor.position === "back" &&
        !actor.token &&
        !(actor.side === "enemy" && barrier && !barrier.elements.includes(source.aff)),
    );
  // A taunt only binds attacks that could land: an immune taunter cannot pin a fight in place.
  const taunters = (source, pool) => pool.filter((actor) => status(actor, "taunt") && !immune(actor, source));
  // Immunity cannot be renewed back to back: a unit that was still immune at the end of its last turn must take
  // at least one enemy turn without it.
  const wardable = (actor) => !status(actor, "immune") && !(actor.warded >= turn - 2);
  const targetsOf = (source, ability, targetId, context) => {
    const effect = ability.effect,
      side = source.side;
    if (effect === "swap") {
      const pool = swapPool(source);
      return [
        pool.find((actor) => actor.id === targetId) ||
          pool.slice().sort((a, b) => b.atk - a.atk || actors.indexOf(a) - actors.indexOf(b))[0],
      ].filter(Boolean);
    }
    if (effect === "shuffle") return [];
    if (offensive(ability)) {
      const pool = live(opponent(side)).filter((actor) => canTarget(source, actor));
      if (ability.target !== "enemy") return pool;
      const taunting = taunters(source, pool);
      return [
        (taunting.length && (taunting.find((actor) => actor.id === targetId) || weakest(taunting))) ||
          pool.find((actor) => actor.id === targetId) ||
          pool.find((actor) => actor.id === context) ||
          weakest(pool),
      ].filter(Boolean);
    }
    if (effect === "revive") {
      const fallen = fallenOf(side);
      return ability.target === "allies"
        ? fallen
        : [fallen.find((actor) => actor.id === targetId) || fallen[0]].filter(Boolean);
    }
    if (ability.target === "self") return [source];
    const pool = live(side);
    if (ability.target === "allies") return pool;
    if (ability.target === "front_row" || ability.target === "back_row")
      return pool.filter((actor) => actor.position === (ability.target === "front_row" ? "front" : "back"));
    const chosen = pool.find((actor) => actor.id === targetId);
    if (chosen) return [chosen];
    const strongest = (list) => [...list].sort((a, b) => b.atk - a.atk || actors.indexOf(a) - actors.indexOf(b))[0];
    // Unplanned immunity goes to a Front Row fighter that can still be warded; a Back Row support cannot be
    // attacked, so warding it would pay for nothing. With none, the cast is not useful and holds unpaid.
    if (effect === "immune") return [strongest(fighters(side).filter(wardable)) || source];
    if (["buff", "taunt"].includes(effect)) return [strongest(fighters(side)) || source];
    return [weakest(pool) || source];
  };
  const trigger = (actor, key, events, context) => {
    const passive = actor.kit?.passive;
    if (
      !passive ||
      actor.token ||
      passive.trigger !== key ||
      actor.triggers.has(key) ||
      depth >= 8 ||
      (passive.row !== "both" && passive.row !== actor.position) ||
      (!actor.alive && key !== "on_death") ||
      // A power-scaled passive with no power (a kit-less enemy's placeholder) does nothing, so it never fires.
      (forgeFormationShares[passive.effect] && !passive.power)
    )
      return;
    actor.triggers.add(key);
    depth += 1;
    events.push({ op: "passive", id: actor.id, name: passive.name });
    effect(actor, passive, null, events, { passive: true, context });
    depth -= 1;
  };
  const triggerAllies = (side, key, except, events, context) => {
    for (const ally of live(side)) if (ally !== except) trigger(ally, key, events, context);
  };
  const collapse = () => {
    if (!fighters("ally").length) return "lose";
    if (!fighters("enemy").length) return "win";
    return null;
  };
  const kill = (actor, source, events) => {
    if (!actor.alive || actor.hp > 0) return;
    const seated = fighters(actor.side).length;
    actor.alive = false;
    actor.shield = 0;
    actor.statuses = [];
    events.push({ op: "death", id: actor.id, killerId: source?.id || "" });
    for (const echo of actors.filter((unit) => unit.ownerId === actor.id && unit.alive)) {
      echo.hp = 0;
      echo.alive = false;
      events.push({ op: "death", id: echo.id, killerId: source?.id || "" });
    }
    if (actor.token) return;
    trigger(actor, "on_death", events);
    if (source?.alive) trigger(source, "on_kill", events);
    triggerAllies(actor.side, "ally_death", actor, events, source?.id);
    // A support takes the seat a fallen fighter leaves, unless a death trigger already refilled it: the next in a
    // defeat order first, then for allies one whose element passes an enemy barrier, then one that can deal damage or
    // wants the Front Row, then seat order. It acts next turn.
    const side = actor.side;
    if (formationRevision < 3 || fighters(side).length >= seated || !seatFree(side, "front")) return;
    stepUp(side, events);
  };
  const stepUp = (side, events) => {
    const [heir] = supports(side).sort((a, b) => rank(a) - rank(b));
    if (!heir) return;
    if (fronts(side).length >= 3) dismissToken(side, events);
    heir.position = "front";
    heir.entered = turn;
    enterRow(heir, events);
  };
  const rank = (unit) =>
    pinned.has(unit.id)
      ? ordered.indexOf(team(unit.side).indexOf(unit)) - ordered.length
      : (unit.side === "ally" && barrier && !barrier.elements.includes(unit.aff) ? 2 : 0) +
        (["front", "hybrid"].includes(unit.kit?.preferredRow) ||
        [unit.kit?.standard, unit.kit?.ultimate].some(
          (skill) => forgeFormationStrikes.has(skill?.effect) || skill?.effect === "dot",
        )
          ? 0
          : 1);
  const dismissToken = (side, events) => {
    const echo = fronts(side).find((actor) => actor.token);
    if (!echo) return;
    echo.alive = false;
    echo.hp = 0;
    events.push({ op: "death", id: echo.id, killerId: "" });
  };
  const summon = (owner, power, events) => {
    if (!owner.alive || fronts(owner.side).length >= 3) return;
    const share = forgeFormationClamp(power, 20, 60) / 100;
    const echo = {
      ...owner,
      id: `${owner.id}~${++tokenSequence}`,
      ownerId: owner.id,
      name: `${owner.name} · Echo`,
      hpMax: Math.max(1, Math.round(owner.hpMax * share)),
      hp: Math.max(1, Math.round(owner.hpMax * share)),
      atk: owner.atk * share,
      def: owner.def * share,
      crit: 0,
      position: "front",
      token: true,
      kit: null,
      mech: [],
      statuses: [],
      shield: 0,
      alive: true,
      acted: true,
      entered: turn,
      triggers: new Set(),
      guard: 0,
      broken: 0,
      charging: "",
      damageBonus: 1,
      critBonus: 0,
    };
    actors.push(echo);
    events.push(
      { op: "summon", id: echo.id, from: owner.id, by: owner.id, position: "front", name: echo.name },
      hpEvent(echo),
    );
  };
  const enterRow = (actor, events) => {
    events.push({ op: "row", id: actor.id, position: actor.position });
    trigger(actor, actor.position === "front" ? "enter_front" : "enter_back", events);
  };
  const strike = (source, target, power, ability, events, passive) => {
    if (immune(target, source)) {
      events.push({ op: "debuff", id: target.id, text: "IMMUNE" });
      return;
    }
    const wheel = { fire: "earth", earth: "wind", wind: "water", water: "fire", light: "dark", dark: "light" },
      affinity = wheel[source.aff] === target.aff ? 1.5 : wheel[target.aff] === source.aff ? 0.75 : 1;
    let chance = source.crit + source.critBonus;
    for (const entry of source.statuses) if (entry.stat === "crit") chance += entry.value;
    const crit = random() * 100 < forgeFormationClamp(chance, 0, 100),
      attack = source.atk * scalar(source, "atk"),
      defense = target.def * scalar(target, "def");
    let amount = Math.max(
      1,
      Math.round(
        attack *
          Math.max(0.2, power / 100) *
          (1 - Math.min(0.8, (defense * 0.4) / Math.max(1, attack * 1.5))) *
          affinity *
          (crit ? source.critDmg / 100 : 1) *
          (ability.effect === "execute" ? 2 - hpShare(target) : 1) *
          source.damageBonus,
      ),
    );
    if (target.broken) amount = Math.round(amount * 1.5);
    amount = Math.round(amount * (1 + fatigue()));
    const blocked = Math.min(target.shield, amount);
    target.shield -= blocked;
    const dealt = amount - blocked;
    target.hp = Math.max(0, target.hp - dealt);
    events.push({
      ...hpEvent(target, "hit", dealt),
      crit,
      effLabel: affinity > 1 ? "STRONG" : affinity < 1 ? "WEAK" : "",
    });
    if (target.guard > 0) {
      target.guard = Math.max(0, target.guard - (affinity > 1 ? 20 : 10));
      events.push({ op: "guard", id: target.id, v: target.guard, max: 100 });
      if (!target.guard) {
        target.broken = 1;
        events.push({ op: "broken", id: target.id });
      }
    }
    if (target.alive && target.hp > 0 && target.mech.includes("phases") && !target.enraged && hpShare(target) < 0.5) {
      target.enraged = true;
      target.atk *= 1.3;
      events.push({ op: "phase", id: target.id });
    }
    if (ability.effect === "drain" && source.alive) heal(source, (dealt * 0.4) / source.hpMax, events);
    kill(target, source, events);
    if (target.alive && !passive) {
      trigger(target, "on_hit", events, source.id);
      triggerAllies(target.side, "ally_hit", target, events, source.id);
    }
  };
  // ponytail: from round 12 healing fades and hits grow 15% a round, so every fight ends; tune with the simulation.
  const fatigue = () => Math.max(0, round - 11) * 0.15;
  const heal = (target, share, events) => {
    if (!target.alive) return;
    const amount = Math.round(target.hpMax * share * Math.max(0, 1 - fatigue()));
    target.hp = Math.min(target.hpMax, target.hp + amount);
    events.push(hpEvent(target, "heal", amount));
  };
  const cleanse = (target) => {
    target.statuses = target.statuses.filter((entry) => !["dot", "stun", "debuff", "silence"].includes(entry.kind));
  };
  const swap = (source, target, events) => {
    if (immune(target, source) || target.mech.includes("immune")) {
      events.push({ op: "debuff", id: target.id, text: "IMMUNE" });
      return;
    }
    const side = target.side;
    if (fronts(side).length >= 3) {
      if (fronts(side).some((actor) => actor.token)) dismissToken(side, events);
      else {
        const leaving = fighters(side)
          .filter((actor) => !pinned.has(actor.id) && !immune(actor, source))
          .sort((a, b) => hpShare(b) - hpShare(a) || actors.indexOf(a) - actors.indexOf(b))[0];
        if (!leaving) {
          events.push({ op: "debuff", id: target.id, text: "RESIST" });
          return;
        }
        leaving.position = "back";
        // From rules 4 both take their seats before the leaving fighter's enter trigger fires (see move).
        if (formationRevision >= 4) {
          target.position = "front";
          target.entered = turn;
          events.push({ op: "row", id: leaving.id, position: "back" }, { op: "row", id: target.id, position: "front" });
          trigger(leaving, "enter_back", events);
          if (target.alive && target.position === "front") trigger(target, "enter_front", events);
          return;
        }
        enterRow(leaving, events);
      }
    }
    target.position = "front";
    target.entered = turn;
    enterRow(target, events);
  };
  const shuffle = (source, events) => {
    const side = opponent(source.side);
    for (const echo of fronts(side).filter((actor) => actor.token)) {
      echo.alive = false;
      echo.hp = 0;
      events.push({ op: "death", id: echo.id, killerId: "" });
    }
    const fixed = live(side).filter((actor) => pinned.has(actor.id) || immune(actor, source));
    const loose = live(side).filter((actor) => !fixed.includes(actor));
    for (let index = loose.length - 1; index > 0; index -= 1) {
      const other = Math.floor(random() * (index + 1));
      [loose[index], loose[other]] = [loose[other], loose[index]];
    }
    const seats = Math.max(
      0,
      Math.min(3, Math.max(1, live(side).filter((actor) => actor.position === "front").length)) -
        fixed.filter((actor) => actor.position === "front").length,
    );
    if (formationRevision >= 3) {
      // Every seat is taken before any enter trigger fires: a trigger can kill, and the support that steps up must
      // keep its seat. A unit that has died or been moved since its seat was taken enters nothing.
      const rows = new Map(loose.map((actor, index) => [actor, index < seats ? "front" : "back"]));
      const moved = loose.filter((actor) => actor.position !== rows.get(actor));
      for (const actor of moved) {
        actor.position = rows.get(actor);
        if (actor.position === "front") actor.entered = turn;
      }
      // From rules 4 every move is also shown before any enter trigger fires, so a unit a trigger kills or revives is
      // drawn where the engine seated it.
      if (formationRevision >= 4) {
        for (const actor of moved) events.push({ op: "row", id: actor.id, position: actor.position });
        for (const actor of moved)
          if (actor.alive && actor.position === rows.get(actor))
            trigger(actor, actor.position === "front" ? "enter_front" : "enter_back", events);
      } else for (const actor of moved) if (actor.alive && actor.position === rows.get(actor)) enterRow(actor, events);
      if (!fighters(side).length) stepUp(side, events);
      return;
    }
    loose.forEach((actor, index) => {
      const row = index < seats ? "front" : "back";
      if (actor.position === row) return;
      actor.position = row;
      if (row === "front") actor.entered = turn;
      enterRow(actor, events);
    });
    if (!fighters(side).length && loose.length) {
      loose[0].position = "front";
      enterRow(loose[0], events);
    }
  };
  function effect(source, ability, targetId, events, { mult = 1, passive = false, context } = {}) {
    const kind = ability.effect,
      power = (Number(ability.power) || 0) * mult,
      chosen = targetsOf(source, ability, targetId, context);
    if (kind === "energy") {
      const amount = Math.max(1, Math.round(power));
      banks[source.side][source.aff] += amount;
      events.push({ op: "energy-gain", id: source.id, element: source.aff, amount }, bankEvent(source.side));
      return;
    }
    if (kind === "summon") return summon(source, power, events);
    if (kind === "shuffle") return shuffle(source, events);
    if (kind === "revive") {
      for (const fallen of chosen) {
        const row = seatFree(fallen.side, fallen.position)
          ? fallen.position
          : fallen.position === "front"
            ? "back"
            : "front";
        if (!seatFree(fallen.side, row)) continue;
        if (row === "front" && fronts(fallen.side).length >= 3) dismissToken(fallen.side, events);
        const fell = fallen.position;
        fallen.alive = true;
        fallen.revived = true;
        fallen.position = row;
        fallen.hp = Math.max(1, Math.round((fallen.hpMax * forgeFormationClamp(power, 10, 100)) / 100));
        fallen.entered = turn;
        fallen.acted = true;
        events.push({ op: "revive", id: fallen.id }, hpEvent(fallen, "heal", fallen.hp));
        // From rules 4 a unit that fell in the Back Row and comes back in front is shown moving there too.
        if (row !== "front" || (formationRevision >= 4 && fell !== row))
          events.push({ op: "row", id: fallen.id, position: row });
      }
      return;
    }
    if (chosen.length > 1 && forgeFormationStrikes.has(kind))
      events.push({ op: "aoe", side: source.side === "ally" ? "enemies" : "allies", color: `var(--${source.aff})` });
    for (const target of chosen) {
      if (!target.alive) continue;
      if (forgeFormationStrikes.has(kind)) strike(source, target, power, ability, events, passive);
      else if (kind === "swap") swap(source, target, events);
      else if (kind === "heal") heal(target, power / 100, events);
      else if (kind === "restore") {
        heal(target, power / 100, events);
        cleanse(target);
        events.push({ op: "buff", id: target.id, text: "RESTORE" });
      } else if (kind === "shield") {
        const cap = target.hpMax * 0.5;
        target.shield = Math.min(cap, Math.max(target.shield, Math.round((target.hpMax * power) / 100)));
        events.push({ op: "shieldFx", ids: [target.id] });
      } else if (kind === "cleanse") {
        cleanse(target);
        events.push({ op: "buff", id: target.id, text: "CLEANSE" });
      } else {
        const hostile = target.side !== source.side;
        if (hostile && (immune(target, source) || (target.mech.includes("immune") && kind !== "taunt"))) {
          events.push({ op: "debuff", id: target.id, text: "IMMUNE" });
          continue;
        }
        // Control cannot chain: a unit that lost its last turn to a stun or silence shrugs off the next one.
        if (kind === "immune" && !wardable(target)) {
          events.push({ op: "debuff", id: target.id, text: "RESIST" });
          continue;
        }
        if ((kind === "stun" || kind === "silence") && (random() * 100 >= power || target.controlled >= turn - 1)) {
          events.push({ op: "debuff", id: target.id, text: "RESIST" });
          continue;
        }
        const value =
          kind === "dot"
            ? Math.max(1, Math.round((source.atk * scalar(source, "atk") * power) / 100))
            : kind === "debuff"
              ? -Math.round(power)
              : Math.round(power);
        addStatus(target, kind, value, ability.duration || 2, source.id, ability.stat);
        events.push({
          op: ["buff", "regen", "immune", "taunt"].includes(kind) ? "buff" : "debuff",
          id: target.id,
          text: kind.toUpperCase(),
        });
      }
    }
  }
  const ultimateOf = (actor) => {
    const ultimate = actor.kit?.ultimate;
    if (!ultimate) return null;
    return trait(actor, "advance_ult") && actor.advanced === turn - 2
      ? { ...ultimate, cost: 0, elementCost: 0, free: true }
      : ultimate;
  };
  const pay = (actor, skill, events) => {
    const bank = banks[actor.side],
      payment = forgeFormationPayment(bank, skill, actor.aff);
    if (!payment) return null;
    if (!skill.cost) return payment;
    for (const key of forgeFormationElements) bank[key] -= payment[key];
    events.push(bankEvent(actor.side));
    // Every point spent adds its element's bonus to this action.
    actor.damageBonus = 1 + 0.05 * payment.fire + 0.08 * payment.dark;
    actor.critBonus = 10 * payment.wind;
    if (payment.earth) {
      actor.shield = Math.min(actor.hpMax * 0.5, actor.shield + Math.round(actor.hpMax * 0.03 * payment.earth));
      events.push({ op: "shieldFx", ids: [actor.id] });
    }
    if (payment.water) heal(weakest(live(actor.side)), 0.03 * payment.water, events);
    if (payment.light) heal(actor, 0.05 * payment.light, events);
    return payment;
  };
  const cast = (actor, skill, ultimate, targetId, events, { free = false, mult = 1, echo = false } = {}) => {
    if (ultimate) {
      events.push({ op: "ult", id: actor.id, name: skill.name, aff: actor.aff, weapon: false });
      trigger(actor, "on_ult", events);
      triggerAllies(actor.side, "ally_ult", actor, events);
    }
    effect(actor, skill, targetId, events, { mult });
    if (forgeFormationStrikes.has(skill.effect)) {
      trigger(actor, "on_attack", events);
      triggerAllies(actor.side, "ally_attack", actor, events);
    }
    // An echo repeats a paid cast once; it never becomes the cast to repeat.
    if (!echo) actor.lastCast = { skill, ultimate, turn };
    actor.damageBonus = 1;
    actor.critBonus = 0;
    if (ultimate && !free && actor.alive)
      for (const counter of fighters(opponent(actor.side)).filter(
        (unit) => unit.mech.includes("counter") && !status(unit, "stun") && !unit.broken,
      )) {
        if (!actor.alive) break;
        events.push({ op: "counter", id: counter.id });
        const normal = counter.kit?.standard;
        effect(
          counter,
          forgeFormationStrikes.has(normal?.effect)
            ? { ...normal, target: "enemy" }
            : { effect: "damage", target: "enemy", power: 100 },
          actor.id,
          events,
          { mult: 0.6, passive: true },
        );
      }
  };
  const ready = (side) => fighters(side).filter((actor) => !actor.acted && actor.entered < turn);
  const moveOptions = (actor) => {
    const side = actor.side,
      moves = [];
    if (pinned.has(actor.id)) return moves;
    if (supports(side).length < 3 && fighters(side).length > 1)
      moves.push({ moveId: actor.id, swapId: null, to: "back" });
    for (const support of supports(side)) moves.push({ moveId: actor.id, swapId: support.id, to: "back" });
    if (seatFree(side, "front"))
      for (const support of supports(side)) moves.push({ moveId: support.id, swapId: null, to: "front" });
    return moves;
  };
  const move = (actor, entry, events) => {
    const legal = moveOptions(actor).find(
      (option) =>
        option.moveId === String(entry.moveId || actor.id) &&
        option.swapId === (entry.swapId ? String(entry.swapId) : null),
    );
    if (!legal) return false;
    const mover = byId(legal.moveId),
      partner = legal.swapId ? byId(legal.swapId) : null;
    if (mover.position === "back" && fronts(actor.side).length >= 3) dismissToken(actor.side, events);
    // From rules 3 each unit's row is fixed up front: the mover's enter trigger can kill, and a support that steps up
    // meanwhile (the partner included) keeps its seat. A unit that died or already arrived is skipped.
    const rows = new Map(
      [mover, partner].filter(Boolean).map((unit) => [unit, unit.position === "front" ? "back" : "front"]),
    );
    // From rules 4 both units take their seats, and show them, before either enter trigger fires, as a shuffle's do,
    // so nothing the mover sets off finds the seat it left open or a fourth support. A unit killed or moved
    // meanwhile enters nothing.
    const seated = formationRevision >= 4;
    if (seated)
      for (const [unit, row] of rows) {
        unit.position = row;
        if (row === "front") {
          unit.entered = turn;
          unit.advanced = turn;
        }
        events.push({ op: "row", id: unit.id, position: row });
      }
    for (const unit of rows.keys()) {
      const row = formationRevision < 3 ? (unit.position === "front" ? "back" : "front") : rows.get(unit);
      const moved = seated ? unit.position !== row : unit.position === row;
      if (formationRevision >= 3 && (!unit.alive || moved)) continue;
      if (!seated && formationRevision >= 3 && row === "front" && fronts(actor.side).length >= 3)
        dismissToken(actor.side, events);
      unit.position = row;
      if (unit.position === "front") {
        unit.entered = turn;
        unit.advanced = turn;
      }
      if (seated) trigger(unit, row === "front" ? "enter_front" : "enter_back", events);
      else enterRow(unit, events);
      const echo = trait(unit, "retreat_echo");
      // Only the cast of its previous own turn is echoed, once.
      if (unit.position === "back" && echo && unit.lastCast?.turn === turn - 2 && !unit.triggers.has("retreat_echo")) {
        unit.triggers.add("retreat_echo");
        cast(unit, unit.lastCast.skill, unit.lastCast.ultimate, null, events, {
          free: true,
          mult: echo.power / 100,
          echo: true,
        });
        unit.lastCast = null;
      }
    }
    if (formationRevision >= 3 && !fighters(actor.side).length) stepUp(actor.side, events);
    return true;
  };
  const useful = (actor, skill, targetId = null) => {
    if (!skill) return false;
    const side = actor.side,
      foes = live(opponent(side));
    switch (skill.effect) {
      case "swap":
        return targetsOf(actor, skill, null).length > 0;
      case "shuffle":
        return foes.filter((foe) => !foe.token).length > 1;
      case "heal":
      case "regen":
        return targetsOf(actor, skill, null).some((ally) => hpShare(ally) < 0.8);
      case "restore":
        return targetsOf(actor, skill, null).some(
          (ally) => hpShare(ally) < 0.65 || status(ally, "dot") || status(ally, "stun"),
        );
      case "revive":
        return fallenOf(side).some(
          (fallen) => seatFree(side, fallen.position) || seatFree(side, fallen.position === "front" ? "back" : "front"),
        );
      case "cleanse":
        return live(side).some((ally) =>
          ally.statuses.some((entry) => ["dot", "stun", "debuff", "silence"].includes(entry.kind)),
        );
      case "summon":
        return fronts(side).length < 3;
      case "immune":
        return targetsOf(actor, skill, targetId).some(wardable);
      default:
        return offensive(skill) ? foes.some((foe) => canTarget(actor, foe)) : true;
    }
  };
  const income = (side) => {
    const gain = forgeFormationZero();
    for (const support of supports(side)) gain[support.aff] += 1;
    return gain;
  };
  const aiTarget = (actor, skill) => {
    if (!offensive(skill) || skill.effect === "swap") return targetsOf(actor, skill, null)[0]?.id;
    const pool = live(opponent(actor.side)).filter((foe) => canTarget(actor, foe));
    const open = pool.filter((foe) => !status(foe, "immune"));
    return weakest(open.length ? open : pool)?.id;
  };
  // One policy plays enemies and Auto: cast the Ultimate when it can be paid, save for it when it lands next turn,
  // else cast the Normal skill, else bring a front-minded support forward, else hold.
  const plan = (side) => {
    const bank = { ...banks[side] },
      soon = income(side),
      entries = [],
      moved = new Set();
    for (const actor of ready(side).filter((unit) => !status(unit, "stun") && !unit.broken)) {
      const normal = actor.kit.standard,
        ultimate = ultimateOf(actor),
        silenced = !!status(actor, "silence");
      const affordable = (skill, extra) =>
        forgeFormationPayment(
          extra ? Object.fromEntries(forgeFormationElements.map((key) => [key, bank[key] + extra[key]])) : bank,
          skill,
          actor.aff,
        );
      let entry = { actorId: actor.id, action: "hold" },
        skill = null,
        saving = false;
      if (!silenced && useful(actor, ultimate) && affordable(ultimate)) {
        entry = { actorId: actor.id, action: "ultimate" };
        skill = ultimate;
      } else if (
        !silenced &&
        !actor.saving &&
        normal.cost > 0 &&
        useful(actor, ultimate) &&
        affordable(ultimate, soon)
      ) {
        saving = true;
      } else if (!silenced && useful(actor, normal) && affordable(normal)) {
        entry = { actorId: actor.id, action: "normal" };
        skill = normal;
      }
      // Saving lasts one turn; a fighter that saved last turn acts now.
      actor.saving = saving;
      if (skill) {
        const payment = affordable(skill);
        for (const key of forgeFormationElements) bank[key] -= payment[key];
        const target = aiTarget(actor, skill);
        if (target) entry.targetId = target;
      } else if (!saving && !pinned.has(actor.id)) {
        const keen = supports(side).filter(
          (support) => ["front", "hybrid"].includes(support.kit?.preferredRow) && !moved.has(support.id),
        );
        if (keen.length && fronts(side).length + moved.size < 3) {
          entry = { actorId: actor.id, action: "row", moveId: keen[0].id };
          moved.add(keen[0].id);
        } else if (keen.length && hpShare(actor) < 0.3 && actor.kit.preferredRow !== "front") {
          entry = { actorId: actor.id, action: "row", moveId: actor.id, swapId: keen[0].id };
          moved.add(keen[0].id);
        }
      }
      entries.push(entry);
    }
    return entries;
  };
  const targetInfo = (actor, skill) => {
    if (!skill) return { kind: "none", ids: [] };
    if (skill.effect === "swap") return { kind: "enemy-back", ids: swapPool(actor).map((foe) => foe.id) };
    if (skill.effect === "shuffle") return { kind: "set", ids: live(opponent(actor.side)).map((foe) => foe.id) };
    if (offensive(skill)) {
      const pool = live(opponent(actor.side)).filter((foe) => canTarget(actor, foe));
      const taunting = skill.target === "enemy" ? taunters(actor, pool) : [];
      return {
        kind: skill.target === "enemy" ? "enemy" : "set",
        ids: (taunting.length ? taunting : pool).map((foe) => foe.id),
        blocked: Object.fromEntries([
          ...live(opponent(actor.side))
            .filter((foe) => !pool.includes(foe))
            .map((foe) => [foe.id, blockedReason(actor, foe) || "back"]),
          // Foes a taunt pulls the attack away from say so.
          ...(taunting.length ? pool.filter((foe) => !taunting.includes(foe)).map((foe) => [foe.id, "taunt"]) : []),
        ]),
        ...(taunting.length ? { taunt: taunting.map((foe) => foe.id) } : {}),
      };
    }
    if (skill.effect === "revive")
      return { kind: skill.target === "allies" ? "set" : "fallen", ids: fallenOf(actor.side).map((ally) => ally.id) };
    // A summon needs a free Front Row seat, and immunity a unit it can still land on.
    if (skill.effect === "summon") return { kind: "set", ids: useful(actor, skill) ? [actor.id] : [] };
    const lands = (ally) => skill.effect !== "immune" || wardable(ally);
    if (skill.target === "ally")
      return {
        kind: "ally",
        ids: live(actor.side)
          .filter(lands)
          .map((ally) => ally.id),
      };
    return {
      kind: "set",
      ids: targetsOf(actor, skill, null)
        .filter(lands)
        .map((ally) => ally.id),
    };
  };
  const options = (side, list) => ({
    v: FORGE_FORMATION_ENGINE,
    round,
    bank: { ...banks[side] },
    income: income(side),
    floor: !supports(side).length,
    fighters: list.map((actor) => {
      const ultimate = ultimateOf(actor);
      return {
        id: actor.id,
        name: actor.name,
        aff: actor.aff,
        preferredRow: actor.kit.preferredRow,
        normal: actor.kit.standard,
        ultimate,
        passive: actor.kit.passive,
        traits: actor.kit.traits,
        silenced: !!status(actor, "silence"),
        targets: { normal: targetInfo(actor, actor.kit.standard), ultimate: targetInfo(actor, ultimate) },
        moves: moveOptions(actor),
      };
    }),
    waiting: fighters(side)
      .filter((actor) => !list.includes(actor))
      .map((actor) => ({ id: actor.id, reason: actor.entered >= turn ? "arrived" : "stunned" })),
    allies: live(side).map((actor) => ({ id: actor.id, position: actor.position, token: actor.token })),
    supports: supports(side).map((actor) => ({ id: actor.id, aff: actor.aff, passive: actor.kit?.passive || null })),
    fallen: fallenOf(side).map((actor) => actor.id),
    foes: live(opponent(side)).map((actor) => ({ id: actor.id, position: actor.position, token: actor.token })),
    rules,
  });
  // A plan is kept as received, less anything that names no ready fighter, so the log replays as the plan.
  const sanitize = (response, list) => {
    if (response?.action !== "plan" || !Array.isArray(response.plan))
      return { v: FORGE_FORMATION_ENGINE, action: "auto" };
    const seen = new Set(),
      entries = [];
    const id = (value) => (typeof value === "string" || typeof value === "number" ? String(value).slice(0, 160) : "");
    for (const raw of response.plan.slice(0, 6)) {
      const actorId = id(raw?.actorId);
      if (
        !actorId ||
        seen.has(actorId) ||
        !list.some((actor) => actor.id === actorId) ||
        !["normal", "ultimate", "row", "hold"].includes(raw.action)
      )
        continue;
      seen.add(actorId);
      entries.push({
        actorId,
        action: raw.action,
        ...(id(raw.targetId) ? { targetId: id(raw.targetId) } : {}),
        ...(raw.action === "row" && id(raw.moveId) ? { moveId: id(raw.moveId) } : {}),
        ...(raw.action === "row" && id(raw.swapId) ? { swapId: id(raw.swapId) } : {}),
      });
    }
    return { v: FORGE_FORMATION_ENGINE, action: "plan", plan: entries };
  };
  const held = (actor, reason, events) => events.push({ op: "formation-held", id: actor.id, reason });
  const resolve = (actor, entry) => {
    const events = [{ op: "act", id: actor.id }];
    actor.acted = true;
    actor.activations += 1;
    const side = actor.side;
    if (actor.mech.includes("charge") && actor.kit?.ultimate) {
      if (actor.charging) {
        const marked = byId(actor.charging);
        actor.charging = "";
        actor.statuses = actor.statuses.filter((entry) => entry.kind !== "charging");
        if (marked) marked.statuses = marked.statuses.filter((entry) => entry.kind !== "marked");
        const target = marked && canTarget(actor, marked) ? marked.id : null;
        cast(actor, actor.kit.ultimate, true, target, events, { free: true, mult: 1.5 });
        events.push(statuses());
        emit(events, 1100);
        return;
      }
      if (actor.activations % 3 === 0) {
        const foe = weakest(live(opponent(side)).filter((unit) => canTarget(actor, unit) && !unit.token));
        if (foe) {
          actor.charging = foe.id;
          addStatus(foe, "marked", 0, 9, actor.id);
          addStatus(actor, "charging", 0, 9, actor.id);
          events.push({ op: "charge", id: actor.id, target: foe.id }, statuses());
          emit(events, 900);
          return;
        }
      }
    }
    let action = entry.action;
    const skill = action === "ultimate" ? ultimateOf(actor) : action === "normal" ? actor.kit.standard : null;
    if (action === "row") {
      if (!move(actor, entry, events)) held(actor, "move", events);
    } else if (!skill) held(actor, "hold", events);
    else if (status(actor, "silence")) held(actor, "silenced", events);
    else if (
      // Immunity is tested on the planned target, which an earlier cast in the same plan may have warded.
      (["revive", "swap", "summon", "immune"].includes(skill.effect) && !useful(actor, skill, entry.targetId)) ||
      (offensive(skill) && skill.effect !== "shuffle" && !targetsOf(actor, skill, entry.targetId).length)
    )
      held(actor, "target", events);
    else if (!pay(actor, skill, events)) held(actor, "energy", events);
    else {
      const free = !skill.cost;
      cast(actor, skill, action === "ultimate", entry.targetId, events, { free });
      if (actor.mech.includes("double") && actor.alive && !collapse()) {
        const normal = actor.kit.standard;
        effect(actor, normal, null, events, { mult: 0.6, passive: true });
      }
    }
    events.push(statuses());
    emit(events, action === "ultimate" ? 1100 : action === "row" ? 600 : 650);
  };
  // A side seated with nobody in front brings its first support forward rather than starting defeated.
  for (const side of ["ally", "enemy"])
    if (!fighters(side).length && supports(side).length) supports(side)[0].position = "front";
  emit([{ op: "start" }, ...actors.map((actor) => hpEvent(actor)), statuses()], 700);
  if (forgeFormationTeamError(allies) || forgeFormationTeamError(enemies) || actors.some((actor) => !actor.kit))
    result = "lose";
  for (round = 1; round <= 40 && !result; round += 1) {
    for (const side of ["ally", "enemy"]) {
      turn += 1;
      for (const actor of actors) actor.triggers.clear();
      const events = round === 12 && side === "ally" ? [{ op: "formation-fatigue", round }] : [],
        bank = banks[side],
        foe = opponent(side);
      // Supports fill the shared bank; a side with none still gains a trickle from its fighters.
      const givers = supports(side);
      if (givers.length) {
        if (fronts(foe).some((unit) => unit.mech.includes("aura")) && round % 3 === 0)
          events.push({ op: "sapped", side });
        else
          for (const support of givers) {
            bank[support.aff] += 1;
            events.push({ op: "energy-gain", id: support.id, element: support.aff, amount: 1 });
          }
      } else {
        // ponytail: +1 every other own turn keeps support-less sides playable; tune with the balance simulation.
        floors[side] += 1;
        const list = fighters(side);
        if (floors[side] % 2 === 0 && list.length) {
          const giver = list[(floors[side] / 2 - 1) % list.length];
          bank[giver.aff] += 1;
          events.push({ op: "energy-gain", id: giver.id, element: giver.aff, amount: 1, floor: true });
        }
      }
      for (const actor of live(side)) {
        actor.acted = false;
        for (const entry of actor.statuses) {
          if (entry.kind === "dot" && actor.alive) {
            if (status(actor, "immune")) continue;
            actor.hp = Math.max(0, actor.hp - entry.value);
            events.push(hpEvent(actor, "hit", entry.value));
            kill(actor, byId(entry.from), events);
          }
          if (entry.kind === "regen" && actor.alive) heal(actor, entry.value / 100, events);
        }
      }
      for (const actor of live(side)) {
        trigger(actor, "turn_start", events);
        const echoes = trait(actor, "front_tokens");
        if (actor.alive && echoes && actor.position === "front")
          for (let count = 0; count < 3 && fronts(side).length < 3; count += 1) summon(actor, echoes.power, events);
        if (actor.alive && actor.mech.includes("summon") && round % 3 === 0) summon(actor, 40, events);
      }
      events.push(bankEvent(side), statuses());
      emit(events, 450);
      result = collapse();
      if (result) break;
      const stunned = [];
      for (const actor of ready(side)) {
        if (status(actor, "stun") || status(actor, "silence")) actor.controlled = turn;
        if (!status(actor, "stun") && !actor.broken) continue;
        actor.acted = true;
        if (actor.broken) actor.broken -= 1;
        actor.statuses = actor.statuses.filter((entry) => entry.kind !== "stun");
        stunned.push({ op: "stun", id: actor.id });
      }
      if (stunned.length) emit([...stunned, statuses()], 450);
      const list = ready(side);
      let entries = [];
      if (list.length && side === "ally") {
        const response = yield {
          op: "choice",
          actor: list[0].id,
          round,
          options: { formation: options(side, list) },
          steps,
          foes: live("enemy").map((unit) => ({
            id: unit.id,
            hp: Math.round(unit.hp),
            hpMax: unit.hpMax,
            atk: Math.round(unit.atk),
            def: Math.round(unit.def),
            spd: unit.spd,
          })),
        };
        const record = sanitize(response, list);
        log.push(record);
        entries = record.action === "plan" ? record.plan : plan(side);
      } else if (list.length) entries = plan(side);
      const quiet = [];
      for (const entry of entries) {
        const actor = list.find((unit) => unit.id === entry.actorId);
        if (!actor || actor.acted || !actor.alive || actor.position !== "front") continue;
        if (entry.action === "hold" && !actor.mech.includes("charge")) {
          actor.acted = true;
          held(actor, "hold", quiet);
          continue;
        }
        resolve(actor, entry);
        result = collapse();
        if (result) break;
      }
      if (!result) {
        for (const actor of ready(side)) {
          actor.acted = true;
          held(actor, "hold", quiet);
        }
        if (quiet.length) emit(quiet, 400);
        const strikes = [];
        for (const echo of fronts(side).filter((unit) => unit.token)) {
          const target = weakest(live(foe).filter((unit) => canTarget(echo, unit)));
          if (!target) continue;
          strikes.push({ op: "act", id: echo.id });
          strike(echo, target, 80, { effect: "damage" }, strikes, true);
          if (collapse()) break;
        }
        if (strikes.length) emit([...strikes, statuses()], 600);
        result = collapse();
      }
      for (const actor of team(side)) if (status(actor, "immune")) actor.warded = turn;
      for (const actor of team(side))
        actor.statuses = actor.statuses.filter((entry) => {
          if (entry.kind === "marked") return byId(entry.from)?.alive && byId(entry.from).charging === actor.id;
          if (entry.kind === "charging") return actor.alive && !!actor.charging;
          if (entry.applied < turn) entry.turns -= 1;
          return entry.turns > 0;
        });
      if (result) break;
    }
  }
  // A stalled puzzle or an invalid client log must never be rewarded as a victory.
  result ||= "lose";
  emit([{ op: "end", result }], 800);
  return { result, steps, log };
}

export function replayForgeFormationBattle(snapshot, choices = []) {
  const list = Array.isArray(choices) ? choices : [];
  const foreign = list.some((choice) => choice && choice.v !== FORGE_FORMATION_ENGINE);
  // The saved snapshot, never the client's log, says which engine a fight was started on. A fight saved before
  // engine 2 carries no stamp and is scored by its own rules; a stamped fight only accepts engine-2 records.
  if (snapshot?.formationEngine == null && foreign && typeof forgeFormationLegacyReplay === "function")
    return forgeFormationLegacyReplay(snapshot, list);
  if (snapshot?.formationEngine === FORGE_FORMATION_ENGINE && foreign) return { result: "lose", steps: [], log: [] };
  const battle = forgeFormationBattle({ ...snapshot, formationRevision: Number(snapshot?.formationRevision) || 2 });
  let index = 0,
    next = battle.next();
  while (!next.done) next = battle.next(list[index++] || { v: FORGE_FORMATION_ENGINE, action: "auto" });
  return next.value;
}
